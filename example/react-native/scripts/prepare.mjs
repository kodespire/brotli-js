// Runs after `npm install`. Replaces the file:../.. link to the repo with the package
// as npm would publish it (`npm pack` of the repo root), so the app builds from the
// published files and autolinking sees exactly what users get. Also writes the test
// fixtures the self-test needs as a JS module (React Native has no file system API),
// with fingerprints of what the package's WebAssembly build compresses
// test/smoke/smoke.mjs's input to: the native module must produce the same bytes.
import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, rmSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(app, '..', '..');

if (!existsSync(join(repo, 'dist', 'entry-react-native.js'))) {
  console.error('brotli-js is not built. In the repo root, run `npm run build:wasm && npm run build:ts` first.');
  process.exit(1);
}

const tmp = mkdtempSync(join(tmpdir(), 'brotli-js-pack-'));
try {
  const packed = JSON.parse(execFileSync('npm', ['pack', '--json', '--pack-destination', tmp], { cwd: repo, encoding: 'utf8' }));
  const tarball = join(tmp, packed[0].filename);
  const target = join(app, 'node_modules', '@kodespire', 'brotli-js');
  // Remove the link itself, never what it points to.
  if (existsSync(target) && lstatSync(target).isSymbolicLink()) unlinkSync(target);
  else rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  execFileSync('tar', ['-xzf', tarball, '-C', target, '--strip-components=1']);
  console.log(`installed ${packed[0].filename} (${packed[0].entryCount} files, ${packed[0].size} bytes packed)`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

const fixtures = [
  'corpus.txt',
  'corpus.stdin.br',
  'corpus.file.br',
  'corpus.q0.br',
  'corpus.q1.br',
  'corpus.q5.br',
  'corpus.q9.br',
  'corpus.w10.br',
  'corpus.large26.br',
  'corpus.comment.br',
  'empty.br',
];
const entries = fixtures.map((name) => {
  const base64 = readFileSync(join(repo, 'test', 'fixtures', name)).toString('base64');
  return `    ${JSON.stringify(name)}: ${JSON.stringify(base64)},`;
});

// The same input and qualities as test/smoke/smoke.mjs (and selftest/run.ts).
const wasm = await import(pathToFileURL(join(app, 'node_modules', '@kodespire', 'brotli-js', 'dist', 'entry-wasm.js')).href);
await wasm.init();
const words = 'the quick brown fox jumps over a lazy dog brotli window block literal distance'.split(' ');
let x = 1;
const smokeText = new TextEncoder().encode(Array.from({ length: 40_000 }, () => {
  x = (Math.imul(x, 1664525) + 1013904223) >>> 0;
  return words[x % words.length] + (x % 13 === 0 ? ` ${x % 1000}\n` : '');
}).join(' '));
const fnv1a = (bytes) => bytes.reduce((h, b) => Math.imul(h ^ b, 0x01000193) >>> 0, 0x811c9dc5);
const fingerprints = [1, 5, 9, 11].map((quality) => {
  const out = wasm.compressSync(smokeText, quality);
  return `    ${quality}: { length: ${out.length}, fnv1a: ${fnv1a(out)} },`;
});

writeFileSync(
  join(app, 'selftest', 'fixtures.generated.js'),
  '// Generated by scripts/prepare.mjs from test/fixtures (base64) and the WebAssembly build. Do not edit.\n' +
    `export default {\n  fixtures: {\n${entries.join('\n')}\n  },\n  wasmFingerprints: {\n${fingerprints.join('\n')}\n  },\n};\n`,
);
